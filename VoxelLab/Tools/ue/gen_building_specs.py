#!/usr/bin/env python3
"""Writes Source/VoxelLab/VLBuildingProps.inl from SourceArt/Meshes/<mesh>.json: the props of every building a Builder
can raise (the barracks' training dummies, a farm's wheat and sheep), so that a building raised in the match gets them
as the level builder gives the level's own (Tools/blender/town_layout.py with_props, Tools/ue/build_level.py place).

    python3 Tools/ue/gen_building_specs.py          (no editor needed; run it again when a building's props change)

Also each building's door (the json's "door": the farmhouse door, where the farm's hands go in and out: UVLConstruction's
farmhands). Positions are converted to Unreal's local space of the building (centimetres, +Y = Blender's -Y, the
building's front) and yaws to Unreal's (minus Blender's). A farm variant (SM_Farmstead_A/B/C) that has no json yet is left out: the game
then falls back to SM_Farmstead.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MESHES = os.path.join(ROOT, "SourceArt", "Meshes")
OUT = os.path.join(ROOT, "Source", "VoxelLab", "VLBuildingProps.inl")
BUILDABLE = ["SM_BarracksYard", "SM_ArcheryHall", "SM_Farmstead", "SM_Farmstead_A", "SM_Farmstead_B", "SM_Farmstead_C", "SM_WatchTower", "SM_MineCliff"]


def main():
    rows, counts, doors = [], {}, []
    for name in BUILDABLE:
        p = os.path.join(MESHES, name + ".json")
        if not os.path.exists(p):
            continue
        meta = json.load(open(p))
        if meta.get("door"):
            x, y, z = meta["door"]
            doors.append('\t{ TEXT("%s"), %.1ff, %.1ff, %.1ff },' % (name, x * 100.0, -y * 100.0, z * 100.0))
        props = meta.get("props", [])
        counts[name] = len(props)
        for pr in props:
            x, y, z = pr["pos"]
            rows.append('\t{ TEXT("%s"), TEXT("%s"), %.1ff, %.1ff, %.1ff, %.1ff, %.3ff },' % (
                name, pr["mesh"], x * 100.0, -y * 100.0, z * 100.0, -float(pr.get("yaw", 0.0)), float(pr.get("scale", 1.0))))
    with open(OUT, "w") as f:
        f.write("// Generated by Tools/ue/gen_building_specs.py from SourceArt/Meshes/*.json: do not edit by hand.\n")
        f.write("// The props of each building a Builder can raise: owner mesh, prop mesh, local X Y Z (cm, Unreal axes), yaw, scale.\n")
        f.write("// %s\n" % ", ".join("%s %d" % kv for kv in counts.items()))
        f.write("static const FVLPropSpec GBuildingProps[] = {\n")
        f.write("\n".join(rows) + "\n")
        f.write("\t{ nullptr, nullptr, 0.f, 0.f, 0.f, 0.f, 1.f }\n};\n")
        f.write("// The door of each building that has one: owner mesh, local X Y Z (cm, Unreal axes).\n")
        f.write("static const FVLDoorSpec GBuildingDoors[] = {\n")
        f.write("".join(d + "\n" for d in doors))
        f.write("\t{ nullptr, 0.f, 0.f, 0.f }\n};\n")
    print("wrote %s: %d props (%s)" % (OUT, len(rows), ", ".join("%s %d" % kv for kv in counts.items())))


if __name__ == "__main__":
    main()
